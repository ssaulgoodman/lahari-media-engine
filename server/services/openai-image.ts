export const generateShotStartFrame = async (opts: {
  visualPrompt: string;
  styleImagePath?: string;
  characterRefs: { name: string; imagePath: string }[];
  environmentRef?: { name: string; imagePath: string };
  prevShotEndFramePath?: string;
  continuityDescription?: string;
  userFeedback?: string;
  failedImagePath?: string;
  aspectRatio?: string;
  additionalRefs?: { imagePath: string }[];
}): Promise<string> => {
  const refs: RefImage[] = [];

  for (const ref of opts.characterRefs) refs.push({ label: `Character: ${ref.name}`, imagePath: ref.imagePath });
  if (opts.styleImagePath) refs.push({ label: 'Style reference', imagePath: opts.styleImagePath });
  if (opts.environmentRef) refs.push({ label: `Environment reference: ${opts.environmentRef.name}`, imagePath: opts.environmentRef.imagePath });
  for (const ref of opts.additionalRefs || []) refs.push({ label: 'Director reference', imagePath: ref.imagePath });
  if (opts.prevShotEndFramePath) refs.push({ label: 'Last-scene continuity reference', imagePath: opts.prevShotEndFramePath });
  if (opts.failedImagePath && opts.userFeedback) {
    refs.push({ label: `PREVIOUS ATTEMPT (rejected). Problems: ${opts.userFeedback}. Do NOT repeat these issues.`, imagePath: opts.failedImagePath });
  }

  let prompt = `Scene: ${opts.visualPrompt}

Preserve character identity from the character references. Match the environment from the environment reference. ${opts.prevShotEndFramePath ? 'Continue visual flow from the continuity reference. ' : ''}Match the visual style exactly from the style reference image.`;

  if (opts.continuityDescription) {
    prompt += `\n\nPrevious shot ended with: ${opts.continuityDescription}
This shot should begin from that exact continuity state — matching pose, camera position, lighting, and mid-action beats — then transition into the scene described above.`;
  }

  if (opts.userFeedback) prompt += `\n\nDirector note: ${opts.userFeedback}`;
  // Medium-neutral — style image is the ground truth. See
  // docs/cinematic-leak-audit-2026-05-12.md.
  prompt += `\n\nSingle frame. No text, no watermark.\nAvoid: overly AI/CGI look, excessive intricate detail, generic fantasy.`;

  const [assetPath] = await generateFromPrompt(prompt, opts.aspectRatio || '16:9', refs, 1);
  return assetPath;
};

export const generateShotEndFrame = async (opts: {
  startFramePath?: string;
  visualPrompt: string;
  motionPrompt: string;
  styleImagePath?: string;
  characterRefs?: { name: string; imagePath: string }[];
  environmentRef?: { name: string; imagePath: string };
  additionalRefs?: { imagePath: string }[];
  userFeedback?: string;
  failedImagePath?: string;
}): Promise<string> => {
  const refs: RefImage[] = [];

  if (opts.startFramePath) refs.push({ label: 'Start frame of this shot', imagePath: opts.startFramePath });
  for (const ref of opts.characterRefs || []) refs.push({ label: `Character: ${ref.name}`, imagePath: ref.imagePath });
  if (opts.styleImagePath) refs.push({ label: 'Style reference', imagePath: opts.styleImagePath });
  if (opts.environmentRef) refs.push({ label: `Environment reference: ${opts.environmentRef.name}`, imagePath: opts.environmentRef.imagePath });
  for (const ref of opts.additionalRefs || []) refs.push({ label: 'Director reference', imagePath: ref.imagePath });
  if (opts.failedImagePath && opts.userFeedback) {
    refs.push({ label: `PREVIOUS END FRAME ATTEMPT (rejected). Problems: ${opts.userFeedback}. Do NOT repeat these issues.`, imagePath: opts.failedImagePath });
  }

  let prompt = `Scene: ${opts.visualPrompt}

Motion: ${opts.motionPrompt}

The first reference image is the start frame of this shot. Generate the ending frame — what the camera sees after the motion described above. Same characters, same costumes, same environment, moments later. Match the visual style exactly from the start frame.`;

  if (opts.userFeedback) prompt += `\n\nDirector note: ${opts.userFeedback}`;
  prompt += `\n\nNo text, no watermark.\nAvoid: overly AI/CGI look, excessive intricate detail, generic fantasy.`;

  const [assetPath] = await generateFromPrompt(prompt, '16:9', refs, 1);
  return assetPath;
};
