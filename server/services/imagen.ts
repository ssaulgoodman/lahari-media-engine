// ─── Shot Start Frame Generation (gemini-3-pro-image-preview) ───────

/**
 * Generate a shot's start frame with full reference chain.
 *
 * Uses a numbered reference index approach — each image is labeled with its role,
 * explicit usage instructions tell the model what to extract from each, and a
 * priority order resolves conflicts between references.
 */
export const generateShotStartFrame = async (opts: {
  visualPrompt: string;
  styleDNA: string;
  styleImagePath?: string;
  characterRefs: { name: string; imagePath: string }[];
  environmentRef?: { name: string; imagePath: string };
  prevShotEndFramePath?: string;
  userFeedback?: string;
}): Promise<string> => {
  const parts: ContentPart[] = [];

  // ── Build reference index ──
  // Number each image so the model can unambiguously refer to them.
  let imageIdx = 0;
  const charImageLabels: string[] = [];

  // Character references (highest priority — identity must be preserved)
  for (const ref of opts.characterRefs) {
    imageIdx++;
    parts.push({ text: `Image ${imageIdx} = Character reference: ${ref.name}` });
    parts.push(imagePartFromPath(ref.imagePath));
    charImageLabels.push(`Image ${imageIdx} (${ref.name})`);
  }

  // Style reference
  if (opts.styleImagePath) {
    imageIdx++;
    parts.push({ text: `Image ${imageIdx} = Style reference` });
    parts.push(imagePartFromPath(opts.styleImagePath));
  }

  // Environment reference
  if (opts.environmentRef) {
    imageIdx++;
    parts.push({ text: `Image ${imageIdx} = Environment reference: ${opts.environmentRef.name}` });
    parts.push(imagePartFromPath(opts.environmentRef.imagePath));
  }

  // Continuity reference (previous shot's end frame)
  if (opts.prevShotEndFramePath) {
    imageIdx++;
    parts.push({ text: `Image ${imageIdx} = Last-scene continuity reference` });
    parts.push(imagePartFromPath(opts.prevShotEndFramePath));
  }

  // ── Reference usage instructions ──
  const usageLines: string[] = [];

  if (charImageLabels.length > 0) {
    usageLines.push(`- Character references (${charImageLabels.join(', ')}): preserve identity, face, hairstyle, silhouette, body proportions, and signature wardrobe details. Do not redesign the character.`);
  }
  if (opts.styleImagePath) {
    usageLines.push('- Style reference: transfer only artistic treatment, lighting logic, palette, texture, lens language, and finish. Do not borrow subject identity from the style reference.');
  }
  if (opts.environmentRef) {
    usageLines.push('- Environment reference: transfer location design, materials, weather, ambience, and spatial cues. Do not change the setting unless required by the scene description.');
  }
  if (opts.prevShotEndFramePath) {
    usageLines.push('- Continuity reference: continue the action, framing logic, emotional beat, and object continuity from the previous shot. The image should feel like a natural continuation.');
  }

  if (usageLines.length > 0) {
    parts.push({ text: `REFERENCE USAGE\n${usageLines.join('\n')}` });
  }

  // ── Scene description ──
  parts.push({ text: `SCENE DESCRIPTION\n${opts.visualPrompt}` });
  parts.push({ text: `Style DNA: ${opts.styleDNA}` });

  if (opts.userFeedback) {
    parts.push({ text: `DIRECTOR FEEDBACK: ${opts.userFeedback}` });
  }

  // ── Output requirements + priority ──
  const outputReqs: string[] = [
    'Generate a single cinematic frame for this scene.'
  ];
  if (opts.prevShotEndFramePath) outputReqs.push('The image must feel like a natural continuation of the continuity reference.');
  if (charImageLabels.length > 0) outputReqs.push('The subject must remain clearly the same character as the character reference(s).');
  if (opts.environmentRef) outputReqs.push('The environment should clearly evoke the environment reference.');
  if (opts.styleImagePath) outputReqs.push('The render should use the visual language of the style reference.');

  parts.push({ text: outputReqs.join('\n') });

  parts.push({ text: `PRIORITY ORDER\n1. Character identity\n2. Temporal continuity with the last scene\n3. Environment fidelity\n4. Style fidelity` });

  parts.push({ text: 'NEGATIVE CONSTRAINTS\n- Do not borrow subject identity from the style reference.\n- Do not redesign the character.\n- Do not change the setting unless required by the scene description.\n- Do not break continuity in costume, pose progression, or major props.\n- No text, no watermark, no logos.' });

  return generateImageWithRefs(parts);
};

// ─── Shot End Frame Generation (gemini-3-pro-image-preview) ──────────

/**
 * Generate a shot's end frame from its start frame + motion prompt.
 * The start frame IS the continuity reference — the end frame shows
 * where the camera/action ends up after the described motion.
 */
export const generateShotEndFrame = async (opts: {
  startFramePath: string;
  motionPrompt: string;
  styleImagePath?: string;
  styleDNA: string;
}): Promise<string> => {
  const parts: ContentPart[] = [];

  // Image 1 = start frame (primary reference)
  parts.push({ text: 'Image 1 = Start frame of this shot (continuity + character + environment reference)' });
  parts.push(imagePartFromPath(opts.startFramePath));

  // Image 2 = style reference (optional)
  if (opts.styleImagePath) {
    parts.push({ text: 'Image 2 = Style reference' });
    parts.push(imagePartFromPath(opts.styleImagePath));
  }

  parts.push({ text: `REFERENCE USAGE
- Image 1 (start frame): This is the beginning of the shot. Preserve character identity, costume, environment, props, and spatial layout exactly. The end frame is the SAME scene moments later.
- ${opts.styleImagePath ? 'Image 2 (style): maintain the same artistic treatment, lighting, palette, and finish.' : `Style DNA: ${opts.styleDNA}`}` });

  parts.push({ text: `MOTION DESCRIPTION\n${opts.motionPrompt}` });

  parts.push({ text: `Generate the END FRAME of this shot — what the camera sees AFTER the motion described above has occurred.

OUTPUT REQUIREMENTS
- Same scene, same characters, same environment as Image 1.
- Camera and/or characters have moved according to the motion description.
- Maintain exact character identity, costume, and props.
- Maintain style consistency.
- No text, no watermark, no logos.

PRIORITY ORDER
1. Character identity continuity with Image 1
2. Environment continuity with Image 1
3. Motion fidelity (show the result of the described movement)
4. Style fidelity` });

  return generateImageWithRefs(parts);
};
