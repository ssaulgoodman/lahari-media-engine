// ─── Character Look Generation (gemini-3-pro-image-preview) ─────────

/**
 * Generate 3 character look variations using gemini-3-pro-image-preview.
 * Uses the locked style image as a visual reference.
 */
export const generateCharacterLooks = async (
  character: { name: string; description: string },
  styleDNA: string,
  styleImagePath?: string,
  userFeedback?: string
): Promise<string[]> => {
  const compositions = [
    'Close-up portrait, looking at camera, detailed face and ornaments',
    'Mid-shot action pose, dynamic composition, full upper body visible',
    'Full body shot, detailed costume and environment, wide framing'
  ];

  const settled = await Promise.allSettled(
    compositions.map(async (composition) => {
      const parts: ContentPart[] = [];

      // Style reference image
      if (styleImagePath) {
        parts.push({ text: 'Generate a character portrait in this visual style:' });
        parts.push(imagePartFromPath(styleImagePath));
      }

      parts.push({ text: `Style: ${styleDNA}` });
      parts.push({ text: `Character: ${character.name} — ${character.description}` });
      parts.push({ text: `Composition: ${composition}` });
      parts.push({ text: 'Cinematic lighting, high detail, film quality. No text, no watermark.' });

      if (userFeedback) {
        parts.push({ text: `FEEDBACK: ${userFeedback}` });
      }

      return generateImageWithRefs(parts);
    })
  );

  const paths: string[] = [];
  for (const result of settled) {
    if (result.status === 'fulfilled') {
      paths.push(result.value);
    } else {
      console.error('[imagen] Character look failed:', result.reason);
    }
  }
  return paths;
};

