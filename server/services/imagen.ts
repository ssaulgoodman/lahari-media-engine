// ─── Shot Start Frame Generation (gemini-3-pro-image-preview) ───────

/**
 * Generate a shot's start frame with full reference chain.
 *
 * Uses a numbered reference index approach — each image is labeled with its role,
 * explicit usage instructions tell the model what to extract from each, and a
 * priority order resolves conflicts between references.
 */
export const generateShotStartFrame = async (opts: {
  visualPrompt: string;
  styleDNA: string;
  styleImagePath?: string;
  characterRefs: { name: string; imagePath: string }[];
  environmentRef?: { name: string; imagePath: string };
  prevShotEndFramePath?: string;
  userFeedback?: string;
}): Promise<string> => {
  const parts: ContentPart[] = [];

  // ── Build reference index ──
  // Number each image so the model can unambiguously refer to them.
  let imageIdx = 0;

  // Character references (highest priority — identity must be preserved)
  for (const ref of opts.characterRefs) {
    imageIdx++;
    parts.push({ text: `Image ${imageIdx} = Character: ${ref.name}` });
    parts.push(imagePartFromPath(ref.imagePath));
  }

  // Style reference
  if (opts.styleImagePath) {
    imageIdx++;
    parts.push({ text: `Image ${imageIdx} = Style reference` });
    parts.push(imagePartFromPath(opts.styleImagePath));
  }

  // Environment reference
  if (opts.environmentRef) {
    imageIdx++;
    parts.push({ text: `Image ${imageIdx} = Environment reference: ${opts.environmentRef.name}` });
    parts.push(imagePartFromPath(opts.environmentRef.imagePath));
  }

  // Continuity reference (previous shot's end frame)
  if (opts.prevShotEndFramePath) {
    imageIdx++;
    parts.push({ text: `Image ${imageIdx} = Last-scene continuity reference` });
    parts.push(imagePartFromPath(opts.prevShotEndFramePath));
  }

  // ── Scene + instructions ──
  let prompt = `Scene: ${opts.visualPrompt}

Style: ${opts.styleDNA}

Preserve character identity from character references. Match environment from environment reference. ${opts.prevShotEndFramePath ? 'Continue visual flow from previous shot. ' : ''}Render in the style of the style reference.`;

  if (opts.userFeedback) {
    prompt += `\n\nDirector note: ${opts.userFeedback}`;
  }

  prompt += `\n\nSingle cinematic frame. No text, no watermark.\nAvoid: overly AI/CGI look, excessive intricate detail, generic fantasy. Should feel like a film still.`;

  parts.push({ text: prompt });

  return generateImageWithRefs(parts);
};

// ─── Shot End Frame Generation (gemini-3-pro-image-preview) ──────────

/**
 * Generate a shot's end frame from its start frame + motion prompt.
 * The start frame IS the continuity reference — the end frame shows
 * where the camera/action ends up after the described motion.
 */
export const generateShotEndFrame = async (opts: {
  startFramePath: string;
  visualPrompt: string;
  motionPrompt: string;
  styleImagePath?: string;
  styleDNA: string;
}): Promise<string> => {
  const parts: ContentPart[] = [];

  parts.push({ text: 'Image 1 = Start frame of this shot' });
  parts.push(imagePartFromPath(opts.startFramePath));

  if (opts.styleImagePath) {
    parts.push({ text: 'Image 2 = Style reference' });
    parts.push(imagePartFromPath(opts.styleImagePath));
  }

  parts.push({ text: `Scene: ${opts.visualPrompt}

Motion: ${opts.motionPrompt}

Style: ${opts.styleDNA}

Image 1 is the start frame of this shot. Generate the ending frame — what the camera sees after the motion described above. Same characters, same costumes, same environment, moments later.

No text, no watermark.
Avoid: overly AI/CGI look, excessive intricate detail, generic fantasy.` });

  return generateImageWithRefs(parts);
};

// ─── Shot Frame Pair Generation (single call, start + end) ───────────

/**
 * Generate both start and end frame in a single API call.
 * The model creates the start frame first, then has perfect memory of it
 * when generating the end frame — much better consistency than two calls.
 *
 * Falls back to separate calls if the model only returns one image.
 */
export const generateShotFramePair = async (opts: {
  visualPrompt: string;
  motionPrompt: string;
  styleDNA: string;
  styleImagePath?: string;
  characterRefs: { name: string; imagePath: string }[];
  environmentRef?: { name: string; imagePath: string };
  prevShotEndFramePath?: string;
  userFeedback?: string;
}): Promise<{ startFramePath: string; endFramePath: string }> => {
  const ai = getAI();
  const parts: ContentPart[] = [];

  // ── Build reference index (same as start frame) ──
  let imageIdx = 0;

  for (const ref of opts.characterRefs) {
    imageIdx++;
    parts.push({ text: `Image ${imageIdx} = Character: ${ref.name}` });
    parts.push(imagePartFromPath(ref.imagePath));
  }

  if (opts.styleImagePath) {
    imageIdx++;
    parts.push({ text: `Image ${imageIdx} = Style reference` });
    parts.push(imagePartFromPath(opts.styleImagePath));
  }

  if (opts.environmentRef) {
    imageIdx++;
    parts.push({ text: `Image ${imageIdx} = Environment: ${opts.environmentRef.name}` });
    parts.push(imagePartFromPath(opts.environmentRef.imagePath));
  }

  if (opts.prevShotEndFramePath) {
    imageIdx++;
    parts.push({ text: `Image ${imageIdx} = Previous shot end frame — match continuity` });
    parts.push(imagePartFromPath(opts.prevShotEndFramePath));
  }

  // ── Prompt for both frames ──
  let prompt = `Scene: ${opts.visualPrompt}

Motion: ${opts.motionPrompt}

Style: ${opts.styleDNA}

Generate TWO images for this shot:

IMAGE 1 — START FRAME: The opening moment of this shot. Preserve character identity from character references. Match environment from environment reference. ${opts.prevShotEndFramePath ? 'Continue visual flow from previous shot. ' : ''}Render in the style of the style reference.

IMAGE 2 — END FRAME: The closing moment of this shot, after the motion described above. Same characters, same costumes, same environment as the start frame, moments later.`;

  if (opts.userFeedback) {
    prompt += `\n\nDirector note: ${opts.userFeedback}`;
  }

  prompt += `\n\nTwo cinematic frames. No text, no watermark.\nAvoid: overly AI/CGI look, excessive intricate detail, generic fantasy. Should feel like film stills.`;

  parts.push({ text: prompt });

  // ── Call model ──
  const response = await ai.models.generateContent({
    model: 'gemini-3-pro-image-preview',
    contents: [{ role: 'user', parts }],
    config: {
      responseModalities: ['IMAGE'],
      // @ts-ignore
      imageConfig: { aspectRatio: '16:9' }
    }
  });

  const images = extractImages(response);

  if (images.length >= 2) {
    console.log(`[shot-frame-pair] Got ${images.length} images in single call`);
    return { startFramePath: images[0], endFramePath: images[1] };
  }

  if (images.length === 1) {
    // Only got start frame — fall back to separate end frame call
    console.warn(`[shot-frame-pair] Only got 1 image, falling back to separate end frame call`);
    const endFramePath = await generateShotEndFrame({
      startFramePath: images[0],
      visualPrompt: opts.visualPrompt,
      motionPrompt: opts.motionPrompt,
      styleImagePath: opts.styleImagePath,
      styleDNA: opts.styleDNA,
    });
    return { startFramePath: images[0], endFramePath };
  }

  throw new Error('No images generated in frame pair call');
};
